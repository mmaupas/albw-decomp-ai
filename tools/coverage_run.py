"""Run Zakuro's interpreter headless over the USA ALBW ROM and write a
coverage log for tools/coverage_rank.py.

  python tools/coverage_run.py [--rom PATH] [--frames N] [--out PATH] [--covtool PATH]
  python tools/coverage_run.py scenario NAME [--frames N] [--replay PATH] [--load STATE]
                               [--save-at FRAME] [--rom PATH] [--covtool PATH] [--no-rank]

The heavy lifting is done by `covtool`, a tiny Rust binary that links
zakuro-core (github.com/fearkov/zakuro) and steps the interpreter
instruction by instruction, counting every PC exactly. covtool is NOT
committed (it lives outside the repo, next to a zakuro checkout with a
small coverage patch applied; see docs/RECOMP_IDEAS.md section 2); this
wrapper just locates it, runs it, and drops the JSONL where coverage_rank.py
expects it.

ROM discovery (first match wins):
  --rom, else $ALBW_ROM, else ~/zakuro-work/albw-usa-synth.3ds (built by
  tools/synth_rom.py from code.bin + the EU container in logs/rom/), else a
  *.3ds under $ALBW_ROMS_DIR or ~/Download
The ROM must be DECRYPTED (Zakuro requires it).

Plain run (legacy): writes logs/coverage/executed.jsonl, one
{"addr": "XXXXXXXX", "hits": N} per executed PC.

Scenario run: plays a scripted input timeline (tools/coverage_scenarios/
NAME.replay, generated by tools/coverage_scenarios.py; the same format
ZAKURO_RECORD writes and ZAKURO_REPLAY plays back) and writes
  logs/coverage/corpus/NAME.jsonl   the coverage of that scenario
  logs/coverage/corpus/NAME.log     covtool's stdout (threads, outcome)
  logs/coverage/states/NAME-F.state an optional ZAKURO_SAVE_AT snapshot to
                                    chain later scenarios from via --load
then re-ranks the whole corpus (executed.jsonl + corpus/*.jsonl) with
coverage_rank.py rank, saving logs/coverage/rank/NAME.txt — the backlog
re-ordered by hotness after each corpus addition.
"""
import argparse
import glob
import os

import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import ROOT

DEFAULT_OUT = os.path.join(ROOT, "logs", "coverage", "executed.jsonl")
DEFAULT_COVTOOL = os.path.expanduser(
    "~/zakuro-work/zakuro-src/target/release/examples/covtool")
SYNTH_ROM = os.path.expanduser("~/zakuro-work/albw-usa-synth.3ds")
SCENARIO_DIR = os.path.join(ROOT, "tools", "coverage-scenarios")
COVERAGE_DIR = os.path.join(ROOT, "logs", "coverage")


def find_rom(args_rom):
    if args_rom:
        return args_rom
    if os.environ.get("ALBW_ROM"):
        return os.environ["ALBW_ROM"]
    if os.path.exists(SYNTH_ROM):
        return SYNTH_ROM
    for d in [os.environ.get("ALBW_ROMS_DIR", ""), os.path.expanduser("~/Download"),
              "/storage/emulated/0/Download"]:
        if not d:
            continue
        hits = sorted(glob.glob(os.path.join(d, "*Link*Between*Worlds*USA*.3ds")))
        if hits:
            return hits[0]
    return None


def scenario_replay_path(name):
    return os.path.join(SCENARIO_DIR, name + ".replay")


def scenario_frames(name, args_frames):
    if args_frames:
        return args_frames
    index_path = os.path.join(SCENARIO_DIR, "index.json")
    if os.path.exists(index_path):
        import json
        with open(index_path, encoding="utf-8") as f:
            entry = json.load(f).get(name)
        if entry:
            return entry["frames"]
    return 600


def run_covtool(covtool, rom, frames, out, data, env_extra, log_path):
    env = dict(os.environ)
    env.update(env_extra)
    cmd = [covtool, rom, str(frames), out, data]
    print(" ".join(cmd))
    with open(log_path, "w", encoding="utf-8") as log:
        rc = subprocess.run(cmd, env=env, stdout=log, stderr=subprocess.STDOUT).returncode
    tail = open(log_path, encoding="utf-8").read().splitlines()
    for line in tail:
        if "covtool result" in line or "distinct PCs" in line or "outcome:" in line:
            print("  " + line)
    if rc == 0 and os.path.exists(out):
        n = sum(1 for _ in open(out))
        print("coverage: %d distinct PCs -> %s" % (n, out))
    return rc


def rank_corpus(name, top=40):
    """re-rank the backlog over the whole corpus after a scenario lands"""
    rank_dir = os.path.join(COVERAGE_DIR, "rank")
    os.makedirs(rank_dir, exist_ok=True)
    out_path = os.path.join(rank_dir, name + ".txt")
    cmd = [sys.executable, os.path.join(ROOT, "tools", "coverage_rank.py"),
           "rank", "--coverage", COVERAGE_DIR, "--top", str(top)]
    proc = subprocess.run(cmd, capture_output=True, text=True, cwd=ROOT)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(proc.stdout)
    print("rank after adding '%s' -> %s" % (name, out_path))
    print("\n".join(proc.stdout.splitlines()[:17]))
    return proc.returncode


def cmd_scenario(args):
    rom = find_rom(args.rom)
    if not rom or not os.path.exists(rom):
        print("no decrypted USA ROM found; pass --rom PATH "
              "(or build the synthetic one: python tools/synth_rom.py)", file=sys.stderr)
        return 2
    if not os.path.exists(args.covtool):
        print("covtool binary not found at %s\n"
              "build it from a zakuro checkout (see docs/RECOMP_IDEAS.md section 2)"
              % args.covtool, file=sys.stderr)
        return 2
    replay = args.replay or scenario_replay_path(args.name)
    frames = scenario_frames(args.name, args.frames)
    corpus_dir = os.path.join(COVERAGE_DIR, "corpus")
    state_dir = os.path.join(COVERAGE_DIR, "states")
    data_dir = args.data or os.path.join(COVERAGE_DIR, "data")
    for d in (corpus_dir, state_dir, data_dir):
        os.makedirs(d, exist_ok=True)
    out = args.out or os.path.join(corpus_dir, args.name + ".jsonl")
    log_path = out + ".log" if args.out else os.path.join(corpus_dir, args.name + ".log")

    env = {}
    if os.path.exists(replay):
        env["ZAKURO_REPLAY"] = replay
        print("replay: %s (%d frames)" % (replay, frames))
    else:
        print("no replay at %s; running with no input" % replay)
    if args.load:
        env["ZAKURO_LOAD"] = args.load
        print("continuing from state %s" % args.load)
    if args.save_at is not None:
        state = os.path.join(state_dir, "%s-%d.state" % (args.name, args.save_at))
        env["ZAKURO_SAVE_AT"] = "%d:%s" % (args.save_at, state)
        print("will save state at frame %d -> %s" % (args.save_at, state))
    if args.dump_at:
        env["ZAKURO_DUMP_AT"] = args.dump_at

    rc = run_covtool(args.covtool, rom, frames, out, data_dir, env, log_path)
    if rc == 0 and not args.no_rank:
        rank_corpus(args.name)
    return rc


def main():
    # accept both `coverage_run.py NAME` and `coverage_run.py scenario NAME`
    argv = sys.argv[1:]
    if argv and argv[0] == "scenario":
        argv = argv[1:]
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("scenario", nargs="?", help="scenario name (tools/coverage-scenarios/NAME.replay)")
    ap.add_argument("--rom")
    ap.add_argument("--frames", type=int, default=None,
                    help="frames to run (default: scenario header, else 600; 600 ~= 10 s)")
    ap.add_argument("--out", default=None,
                    help="output JSONL (default: executed.jsonl, or corpus/<name>.jsonl in scenario mode)")
    ap.add_argument("--covtool", default=DEFAULT_COVTOOL)
    ap.add_argument("--data", default=None, help="zakuro data dir (saves etc.); scenario default logs/coverage/data")
    ap.add_argument("--replay", help="input replay file (default tools/coverage-scenarios/NAME.replay)")
    ap.add_argument("--load", help="ZAKURO_LOAD state file to continue from")
    ap.add_argument("--save-at", type=int, help="ZAKURO_SAVE_AT frame to snapshot a state")
    ap.add_argument("--dump-at", help="ZAKURO_DUMP_AT frames to dump screens (PPM) at")
    ap.add_argument("--no-rank", action="store_true", help="skip the coverage_rank.py re-rank")
    args = ap.parse_args(argv)

    if args.scenario:
        args.name = args.scenario
        return cmd_scenario(args)

    rom = find_rom(args.rom)
    if not rom or not os.path.exists(rom):
        print("no decrypted USA ROM found; pass --rom PATH", file=sys.stderr)
        return 2
    if not os.path.exists(args.covtool):
        print("covtool binary not found at %s\n" % args.covtool +
              "build it from a zakuro checkout (see docs/RECOMP_IDEAS.md section 2)",
              file=sys.stderr)
        return 2
    frames = args.frames or 600
    args.out = args.out or DEFAULT_OUT
    out_dir = os.path.dirname(os.path.abspath(args.out))
    if out_dir:
        os.makedirs(out_dir, exist_ok=True)
    data = args.data or os.path.expanduser("~/zakuro-work/cov-data")
    os.makedirs(data, exist_ok=True)
    print("rom: %s\nframes: %d\nout: %s" % (rom, frames, args.out))
    return run_covtool(args.covtool, rom, frames, args.out, data, {},
                       args.out + ".log")


if __name__ == "__main__":
    sys.exit(main())
