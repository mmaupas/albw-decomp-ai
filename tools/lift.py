#!/usr/bin/env python
"""ARM32 semantic lifter (Hookshot-style): unmatched functions -> C scaffolds.

  python tools/lift.py lift <addr> [--image PATH] [--force] [--json]
  python tools/lift.py batch [--limit N] [--budget B] [--filter ...] [--min-size N] [--json]
  python tools/lift.py targets [--filter ...] [--min-size N] [--limit N] [--json]
  python tools/lift.py status [--json]
  python tools/lift.py report [--json]

Lifted code is SEMANTIC, never byte-exact: a lifted source is never
registered as matched/honest and never counts in any matched statistic.
Its purpose is oracle coverage, hybrid builds, and a starting scaffold
for later matching work. Lifting records status "lifted" in
functions.json with the src_lifted/ path; nothing else is ever touched.

Method: the function is disassembled with capstone in ARM mode
(ARMv6K, --cpu=MPCore) from its start to the next start (the
consecutive-starts convention of funcs.json). Literal-pool words are
split from instructions exactly like fn.py code_end / shapemine (PC-
relative LDR targets are POOL), and instruction tokens reuse
shapemine.token_of (cond stripped, regs->r, imms->#, pools->POOL,
calls->CALL) so lifted analysis composes with the shape tools. A
per-function CFG is built from branch targets; each block is emitted as
C with labels. The machine is modeled explicitly and conservatively:
r0-r3 are parameters, r4-r12/sp/lr are zero-initialized C locals, NZCV
are flag locals, the frame is a local byte array addressed through sp,
calls to known starts become `extern u32 func_XXXXXXXX(u32,u32,u32,u32)`
declarations (repo naming convention), calls to non-starts (e.g.
__aeabi_idiv/__aeabi_uidiv/__aeabi_idivmod division helpers) become
opaque externs with a logged warning, tail `b` to another start becomes
a plain call, `bx lr`/`pop {pc}` become `return r0;`, and
`ldr pc,[pc,rX,lsl#2]` jump tables become a switch. Any construct that
cannot be expressed safely makes the whole function a clearly marked
/* LIFT-UNSUPPORTED */ stub (frame preserved, fixed return value) with
the reason recorded in the batch state - a correct gap is acceptable, a
wrong lift is not.

Output compiles under armcc 4.1 b1049 with the repo default flags
(conservative C99, no GNU extensions). Every file starts with the
LIFTED banner and lives at src_lifted/func_<ADDR>.c.

State: logs/lift/state.json (resumable; gitignored). --image overrides
the binary (default: SHA-1-verified code.bin, read-only); without it,
`lift`/`batch` degrade to a printed plan with the exact commands to run
on the phone. `targets`/`status`/`report` are fully offline.
"""
