def lift_targets(functions, starts, filters, min_size=0, limit=0):
    """Offline liftable-address listing: [{addr, size, reason, twin}]."""
    want = set(filters) or {"unmatched", "source_lost"}
    reasons = want - {"all", "no_twin"}
    dna_index = None
    if "no_twin" in want:
        dna_path = os.path.join(ROOT, "logs", "dna.jsonl")
        if os.path.exists(dna_path):
            import dna as dna_mod
            dna_index = {r["addr"]: r for r in dna_mod.load_index()}
    ops_twins = {}
    if dna_index is not None:
        for r in dna_index.values():
            ent = functions.get(r["addr"])
            if ent and ent.get("path") and ent.get("status") in ("honest", "hack"):
                ops_twins.setdefault(r["ops"], ent["path"])
    out = []
    for i, addr in enumerate(starts):
        key = "%08X" % addr
        ent = functions.get(key)
        if ent is not None and ent.get("status") in ("honest", "hack", "lifted", "semantic_match",
                                                     "excluded", "excluded_library", "interior_address"):
            continue
        size = (starts[i + 1] if i + 1 < len(starts) else TEXT_START + TEXT_SIZE) - addr
        if ent is None:
            reason = "unmatched"
        elif ent.get("label") == "source_lost":
            reason = "source_lost"
        else:
            reason = ent.get("status", "?")
        if min_size and size < min_size:
            continue
        if reasons and reason not in reasons and "all" not in want:
            continue
        twin = None
        if dna_index is not None:
            rec = dna_index.get(key)
            if rec:
                twin = ops_twins.get(rec["ops"])
        if "no_twin" in want and twin:
            continue
        out.append({"addr": key, "size": size, "reason": reason, "twin": twin})
        if limit and len(out) >= limit:
            break
    out.sort(key=lambda r: (r["size"], r["addr"]))
    return out


