def load_functions():
    return read_json(FUNCTIONS)


def load_starts():
    return read_json(FUNCS)["starts"]


def load_symbols():
    out = {}
    if os.path.exists(SYMBOLS):
        with open(SYMBOLS, encoding="utf-8") as fh:
            for line in fh:
                try:
                    d = json.loads(line)
                    if d.get("name"):
                        out[int(d["addr"], 16)] = d["name"]
                except (ValueError, KeyError, TypeError):
                    pass
    return out


def record_lifted(key, rel_path, cc=DEFAULT_CC, flags=DEFAULT_FLAGS):
    """Record status "lifted" in functions.json. Never touches other entries."""
    with file_lock(LOCK):
        data = load_functions()
        ent = data.get(key)
        if ent and ent.get("status") != "lifted":
            raise ValueError("refusing to overwrite existing %s entry %s" % (ent.get("status"), key))
        data[key] = {"cc": cc, "flags": flags, "path": rel_path, "status": "lifted"}
        write_json(FUNCTIONS, data, canonical=True)


def load_state():
    if os.path.exists(STATE_FILE):
        return read_json(STATE_FILE)
    return {"lifted": {}, "runs": 0}


def save_state(state):
    write_json(STATE_FILE, state)


def lift_path(key):
    return os.path.join("src_lifted", "func_%s.c" % key)


def load_image(path=None):
    """Default: the SHA-1-verified, read-only code.bin. --image: raw file."""
    if path is None:
        if not os.path.exists(CODE_BIN):
            return None
        return Image(load_binary(CODE_BIN))
    with open(path, "rb") as fh:
        return Image(fh.read())


