# --------------------------------------------------------------- disassembly

_md = None


def disasm_one(img, addr):
    """Decode the single ARM word at addr (None if not a valid instruction)."""
    global _md
    if Cs is None:
        raise RuntimeError("lifting requires capstone; install it with `uv sync`")
    if _md is None:
        _md = Cs(CS_ARCH_ARM, CS_MODE_ARM)
    off = addr - img.ta
    if off < 0 or off + 4 > len(img.data):
        return None
    hit = list(_md.disasm(img.data[off:off + 4], addr, 1))
    return hit[0] if hit else None


class Image:
    """A flat code image with its .text base (fixture-friendly, no SHA check)."""

    def __init__(self, data, text_start=TEXT_START):
        self.data = data
        self.ta = text_start

    def word(self, addr):
        off = addr - self.ta
        if off < 0 or off + 4 > len(self.data):
            raise ValueError("address %08X outside image" % addr)
        return struct.unpack_from("<I", self.data, off)[0]

    def try_word(self, addr):
        off = addr - self.ta
        if off < 0 or off + 4 > len(self.data):
            return None
        return struct.unpack_from("<I", self.data, off)[0]


def pool_words(img, start, end, starts=()):
    """Words inside [start,end) that are data, not instructions: PC-relative
    LDR pool targets and jump-table entries after `ldr pc,[pc,rX,lsl#2]`
    (the same splits fn.py code_end / listing use)."""
    pool = set()
    for a in range(start, end, 4):
        if img.try_word(a) is None:
            break
        ins = disasm_one(img, a)
        if ins is not None:
            m = re.search(r"\[pc, #(-?0x[0-9a-f]+|-?\d+)\]", ins.op_str)
            if m and ins.mnemonic.replace("v", "", 1).startswith("ldr"):
                tgt = ins.address + 8 + int(m.group(1), 0)
                if start <= tgt < end:
                    pool.add(tgt & ~3)
        w = img.word(a)
        if (w & 0x0FFFFFF0) == 0x079FF100:  # ldr pc, [pc, rX, lsl #2]: switch table follows
            j = a + 8
            while j < end and img.try_word(j) is not None and (
                    start <= img.word(j) < end or img.word(j) in starts):
                pool.add(j)
                j += 4
    return pool


def code_end(img, start, end, starts=()):
    """Split [start,end) into instructions and trailing literal pool."""
    pool = pool_words(img, start, end, starts)
    ce = end
    while ce - 4 >= start and (ce - 4) in pool:
        ce -= 4
    return ce, pool


def split_cond(mnemonic):
    """'ldrne' -> ('ldr', 'ne'); 'teq' stays ('teq', 'al'); 'b' -> ('b', 'al')."""
    if mnemonic in PLAIN:
        return mnemonic, "al"
    for c in sorted(shapemine._COND, key=len, reverse=True):
        if mnemonic.endswith(c) and len(mnemonic) > len(c):
            return mnemonic[:-len(c)], c
    return mnemonic, "al"


COND_EXPR = {
    "eq": "fZ", "ne": "!fZ", "cs": "fC", "hs": "fC", "cc": "!fC", "lo": "!fC",
    "mi": "fN", "pl": "!fN", "vs": "fV", "vc": "!fV",
    "hi": "(fC && !fZ)", "ls": "(!fC || fZ)", "ge": "(fN == fV)", "lt": "(fN != fV)",
    "gt": "(!fZ && fN == fV)", "le": "(fZ || fN != fV)", "al": None,
}

REGNAME = {"sb": "r9", "sl": "r10", "fp": "r11", "ip": "r12",
           "sp": "sp", "lr": "lr", "pc": "pc"}


def reg(tok):
    tok = tok.strip()
    return REGNAME.get(tok, tok)


def parse_int(tok):
    tok = tok.strip()
    if tok.startswith("#"):
        tok = tok[1:]
    return int(tok, 0)


def reg_list(text):
    """'{r4, r5, lr}' (or the tail of 'sp!, {r4, lr}') -> ['r4', 'r5', 'lr']."""
    inner = text.split("!")[-1].strip()
    if inner.startswith("{"):
        inner = inner[1:]
    if inner.endswith("}"):
        inner = inner[:-1]
    return [reg(t) for t in inner.split(",") if t.strip()]


def branch_target(ins):
    """Immediate target of b/bl/blx (capstone prints absolute addresses), or
    None for register forms."""
    base, _ = split_cond(ins.mnemonic)
    if base in ("b", "bl", "blx") and ins.op_str.startswith("#"):
        return parse_int(ins.op_str)
    return None


def is_branch(ins):
    base, _ = split_cond(ins.mnemonic)
    return base in ("b", "bl", "blx", "bx")


def is_return(ins):
    base, _ = split_cond(ins.mnemonic)
    ops = ins.op_str
    if base == "bx" and reg(ops) == "lr":
        return True
    if base == "mov" and ops.split(",")[0].strip() == "pc":
        return True
    if base == "ldr" and ops.split(",")[0].strip() == "pc":
        return True
    if base in ("pop", "ldmia", "ldmfd") and "pc" in reg_list(ops):
        return True
    return False


# ------------------------------------------------------------------- CFG

def build_cfg(img, start, end, starts=()):
    """Basic blocks of [start, code_end). Returns (blocks, ce, pool).

    blocks: list of {addr, insns, succs} sorted by addr; succs are
    (kind, target) pairs for analysis (goto/call/tail/return/fall).
    """
    ce, pool = code_end(img, start, end, starts)
    insns = []
    for a in range(start, ce, 4):
        if a in pool:
            continue  # interior data (jump table): not an instruction
        ins = disasm_one(img, a)
        if ins is None:
            raise Unsupported("undecodable word at %08X" % a)
        insns.append(ins)
    leaders = {start}
    for ins in insns:
        t = branch_target(ins)
        if t is not None and start <= t < ce:
            leaders.add(t)
        if (is_branch(ins) or is_return(ins)) and ins.address + 4 < ce:
            leaders.add(ins.address + 4)
    blocks, cur = [], None
    for ins in insns:
        if cur is None or ins.address in leaders:
            cur = {"addr": ins.address, "insns": [], "succs": []}
            blocks.append(cur)
        cur["insns"].append(ins)
    for blk in blocks:
        last = blk["insns"][-1]
        t = branch_target(last)
        base, _ = split_cond(last.mnemonic)
        nxt = blk["addr"] + 4 * len(blk["insns"])
        if t is not None and start <= t < ce:
            blk["succs"].append(("goto" if base == "b" else "call", t))
        elif t is not None and base in ("b", "bl"):
            blk["succs"].append(("tail", t))
        elif base in ("bx", "blx") or is_return(last):
            blk["succs"].append(("return", None))
        if not (is_branch(last) or is_return(last)) and nxt < ce:
            blk["succs"].append(("fall", nxt))
    return blocks, ce, pool


