MACROS = """#define LIFT_LD8(a)   (*(const u8*)(a))
#define LIFT_LD16(a)  (*(const u16*)(a))
#define LIFT_LD32(a)  (*(const u32*)(a))
#define LIFT_LDS8(a)  ((s32)(s8)(*(const u8*)(a)))
#define LIFT_LDS16(a) ((s32)(s16)(*(const u16*)(a)))
#define LIFT_ST8(a, v)  (*(u8*)(a) = (u8)(v))
#define LIFT_ST16(a, v) (*(u16*)(a) = (u16)(v))
#define LIFT_ST32(a, v) (*(u32*)(a) = (u32)(v))"""


def frame_size(blocks):
    """Conservative frame: every pushed register + the largest sub sp, + slack."""
    push_regs, max_sub = 0, 0
    for blk in blocks:
        for ins in blk["insns"]:
            base, _ = split_cond(ins.mnemonic)
            if base in ("push", "stmdb", "stmfd"):
                push_regs += len(reg_list(ins.op_str))
            elif base == "sub" and ins.op_str.replace(" ", "").startswith("sp,sp,#"):
                max_sub = max(max_sub, parse_int(ins.op_str.split("#")[-1]))
    return 4 * push_regs + max_sub + 64


def uses_sp(blocks):
    for blk in blocks:
        for ins in blk["insns"]:
            if "sp" in ins.op_str or split_cond(ins.mnemonic)[0] in ("push", "pop", "stmdb", "stmfd", "ldmia", "ldmfd"):
                return True
    return False


def lift_function(img, starts, addr, symbols=None):
    """Lift one function start to C text. Pure apart from capstone.

    Returns {text, warnings, unsupported, size, n_insns, externs, tokens}.
    """
    starts = sorted(starts)
    i = bisect.bisect_right(starts, addr) - 1
    if i < 0 or starts[i] != addr:
        raise ValueError("lift requires an exact function start: %08X" % addr)
    end = starts[i + 1] if i + 1 < len(starts) else TEXT_START + TEXT_SIZE
    end = min(end, img.ta + len(img.data))  # fixture images may be shorter than .text
    symbols = symbols or {}
    blocks, ce, pool = build_cfg(img, addr, end, starts)
    ctx = {"img": img, "start": addr, "end": end, "ce": ce, "starts": set(starts),
           "syms": symbols, "warnings": [], "flags_set": False, "externs": {}}

    def ext_name(t, at=None):
        if t in ctx["starts"] or t == end:
            name = symbols.get(t, "func_%08X" % t)
        else:
            # non-start call target: compiler helper (e.g. __aeabi_idiv/uidiv/idivmod)
            name = symbols.get(t, "lift_helper_%08X" % t)
            ctx["warnings"].append(
                "call to non-start %08X at %08X modeled as opaque extern %s (possible __aeabi_* helper)"
                % (t, at or 0, name))
        ctx["externs"][name] = t
        return name

    ctx["ext_name"] = ext_name
    unsupported = None
    body = []
    try:
        for blk in blocks:
            if blk["addr"] != addr:
                body.append("L_%08X:" % blk["addr"])
            for ins in blk["insns"]:
                body.extend(translate(ins, ctx))
        if not body or not body[-1].lstrip().startswith("return"):
            body.append("return r0;")
    except Unsupported as exc:
        unsupported = str(exc)
        ctx["warnings"].append("LIFT-UNSUPPORTED: %s" % unsupported)

    tokens = [shapemine.token_of(ins.mnemonic, ins.op_str)
              for blk in blocks for ins in blk["insns"]]

    key = "%08X" % addr
    lines = [BANNER % key, '#include "albw_types.h"', "", MACROS, ""]
    for name in sorted(ctx["externs"]):
        lines.append("extern u32 %s(u32, u32, u32, u32);" % name)
    if ctx["externs"]:
        lines.append("")
    lines.append("u32 func_%s(u32 r0, u32 r1, u32 r2, u32 r3) {" % key)
    lines.append("    u32 %s;" % ", ".join("r%d = 0" % n for n in range(4, 13)))
    if uses_sp(blocks):
        frame = frame_size(blocks)
        lines.append("    u8 stack[%d];" % frame)
        lines.append("    u32 sp = (u32)(stack + %d);" % frame)
    else:
        lines.append("    u32 sp = 0;")
    lines.append("    u32 lr = 0;")
    lines.append("    u32 fN = 0, fZ = 0, fC = 0, fV = 0;")
    if unsupported is not None:
        lines.append("    /* LIFT-UNSUPPORTED: %s" % unsupported)
        lines.append("     * Frame preserved, fixed return value: correct gap, not a lift. */")
        lines.append("    return 0;")
    else:
        lines.extend("    " + l for l in body)
    lines.append("}")
    lines.append("")
    return {"text": "\n".join(lines), "warnings": ctx["warnings"], "unsupported": unsupported,
            "size": end - addr, "n_insns": sum(len(b["insns"]) for b in blocks),
            "externs": sorted(ctx["externs"]), "tokens": tokens,
            "n_call": sum(1 for t in tokens if "CALL" in t),
            "n_pool": sum(1 for t in tokens if "POOL" in t)}


