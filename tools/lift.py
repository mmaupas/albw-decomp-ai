def _do_lift(addr, img, starts, force=False):
    """Lift one address end-to-end (file + ledger + state). Returns a dict."""
    key = "%08X" % addr
    functions = load_functions()
    ent = functions.get(key)
    if ent and ent.get("status") != "lifted" and not force:
        raise ValueError("refusing to lift over existing %s entry %s" % (ent.get("status"), key))
    result = lift_function(img, starts, addr, load_symbols())
    rel = lift_path(key)
    dest = os.path.join(ROOT, rel)
    if os.path.exists(dest) and not force:
        raise ValueError("lifted file already exists (use --force): " + rel)
    atomic_write(dest, result["text"])
    record_lifted(key, rel)
    state = load_state()
    state["lifted"][key] = {"path": rel, "size": result["size"], "n_insns": result["n_insns"],
                            "unsupported": result["unsupported"], "warnings": result["warnings"],
                            "externs": result["externs"], "n_call": result["n_call"],
                            "n_pool": result["n_pool"]}
    state["runs"] = state.get("runs", 0) + 1
    save_state(state)
    return {"addr": key, "path": rel, "status": "lifted", "size": result["size"],
            "n_insns": result["n_insns"], "unsupported": result["unsupported"],
            "warnings": result["warnings"]}


def cmd_lift(addr, image_path=None, force=False, as_json=False):
    key = "%08X" % addr
    starts = load_starts()
    if addr not in starts:
        raise ValueError("lift requires an exact function start: %s" % key)
    img = load_image(image_path)
    if img is None:
        print(PHONE_HINT)
        return 2
    out = _do_lift(addr, img, starts, force=force)
    if as_json:
        print(json.dumps(out))
    else:
        print("LIFTED %s -> %s (%d bytes, %d insns%s)" % (
            key, out["path"], out["size"], out["n_insns"],
            ", LIFT-UNSUPPORTED: " + out["unsupported"] if out["unsupported"] else ""))
        for w in out["warnings"]:
            print("WARN   %s" % w)
        print("NEXT  python tools/audit.py  # lifted entries are disjoint from matched; audit must stay CLEAN")
    return 0


def cmd_batch(limit, budget, filters, min_size, image_path=None, as_json=False):
    img = load_image(image_path)
    if img is None:
        print(PHONE_HINT)
        return 2
    starts = load_starts()
    functions = load_functions()
    targets = lift_targets(functions, starts, filters, min_size, limit)
    state = load_state()
    done, lifted_keys = 0, []
    for t in targets:
        if done >= budget:
            break
        if t["addr"] in state["lifted"]:
            continue
        out = _do_lift(int(t["addr"], 16), img, starts, force=True)
        done += 1
        lifted_keys.append(out["addr"])
        print("lifted %s (%d/%d)" % (out["addr"], done, budget), file=sys.stderr)
    state = load_state()
    pending = sum(1 for t in targets if t["addr"] not in state["lifted"])
    out = {"budget": budget, "lifted_this_run": done, "lifted_addrs": lifted_keys,
           "total_lifted": len(state["lifted"]), "pending_in_selection": pending}
    if as_json:
        print(json.dumps(out))
    else:
        print("batch: lifted %d (budget %d), %d lifted total, %d pending in selection" % (
            done, budget, out["total_lifted"], pending))
        print("NEXT  python tools/lift.py report --json")
    return 0


def cmd_targets(filters, min_size, limit, as_json=False):
    starts = load_starts()
    functions = load_functions()
    rows = lift_targets(functions, starts, filters, min_size, limit)
    if as_json:
        print(json.dumps(rows))
    else:
        print("liftable targets (%d%s):" % (len(rows), ", --limit %d" % limit if limit else ""))
        for r in rows[:40]:
            print("  %s  %6d B  %-12s %s" % (r["addr"], r["size"], r["reason"],
                                             "twin:" + r["twin"] if r["twin"] else "no-twin"))
        if len(rows) > 40:
            print("  ... %d more" % (len(rows) - 40))
        print("NEXT  python tools/lift.py batch --limit %d --budget %d" % (limit or 200, DEFAULT_BUDGET))
    return 0


def cmd_status(as_json=False):
    functions = load_functions()
    starts = load_starts()
    lifted = sum(1 for v in functions.values() if v.get("status") == "lifted")
    state = load_state()
    pending = len(lift_targets(functions, starts, ("all",)))
    out = {"lifted": lifted, "pending_targets": pending,
           "unsupported": sum(1 for v in state["lifted"].values() if v.get("unsupported")),
           "runs": state.get("runs", 0)}
    if as_json:
        print(json.dumps(out))
    else:
        print("lift: %d lifted, %d pending targets, %d unsupported stubs, %d runs" % (
            out["lifted"], out["pending_targets"], out["unsupported"], out["runs"]))
        print("NEXT  python tools/lift.py report  # or batch --budget %d to continue" % DEFAULT_BUDGET)
    return 0


def cmd_report(as_json=False):
    state = load_state()
    rows = []
    for key, rec in sorted(state["lifted"].items()):
        rows.append({"addr": key, "path": rec["path"], "size": rec["size"],
                     "n_insns": rec["n_insns"], "unsupported": rec.get("unsupported"),
                     "n_warnings": len(rec.get("warnings", [])),
                     "externs": rec.get("externs", [])})
    out = {"lifted": len(rows), "unsupported": sum(1 for r in rows if r["unsupported"]),
           "functions": rows}
    if as_json:
        print(json.dumps(out))
    else:
        print("lifted report (%d, %d unsupported stubs):" % (out["lifted"], out["unsupported"]))
        for r in rows[:40]:
            print("  %s  %6d B  %4d insns  %s%s" % (
                r["addr"], r["size"], r["n_insns"], r["path"],
                "  LIFT-UNSUPPORTED: " + r["unsupported"] if r["unsupported"] else ""))
        if len(rows) > 40:
            print("  ... %d more" % (len(rows) - 40))
        print("NEXT  python tools/hybrid_build.py --check  # composition plan over funcs.json + functions.json")
    return 0


