WIDTH = {"ldr": (32, "LIFT_LD32", "LIFT_ST32"),
         "str": (32, "LIFT_LD32", "LIFT_ST32"),
         "ldrb": (8, "LIFT_LD8", "LIFT_ST8"),
         "strb": (8, "LIFT_LD8", "LIFT_ST8"),
         "ldrh": (16, "LIFT_LD16", "LIFT_ST16"),
         "strh": (16, "LIFT_LD16", "LIFT_ST16"),
         "ldrsb": (8, "LIFT_LDS8", None),
         "ldrsh": (16, "LIFT_LDS16", None)}

ADDR_RE = re.compile(r"^(\w+), \[(\w+)(?:, ([^\]]+))?\](!)?(?:, (.+))?$")


def shifter(op2, allow_carry=True):
    """Parse a shifter operand ('#imm', 'rm', 'rm, lsl #n', 'rm, lsl rs', ...)
    -> (expr, carry_expr_or_None)."""
    op2 = op2.strip()
    if op2.startswith("#"):
        return "0x%Xu" % (parse_int(op2) & 0xFFFFFFFF), None
    parts = [p.strip() for p in op2.split(",")]
    rm = reg(parts[0])
    if len(parts) == 1:
        return rm, None
    tail = " ".join(parts[1:]).split()
    kind, amt = tail[0], (tail[1] if len(tail) > 1 else "")
    if amt and not amt.startswith("#"):
        rs = reg(amt)  # shift amount in a register
        if not allow_carry:
            raise Unsupported("flag-setting shift by register %r" % op2)
        if kind.startswith("lsl"):
            return "((u32)(%s) << ((%s) & 31u))" % (rm, rs), None
        if kind.startswith("lsr"):
            return "((u32)(%s) >> ((%s) & 31u))" % (rm, rs), None
        if kind.startswith("asr"):
            return "((u32)((s32)(%s) >> ((%s) & 31u)))" % (rm, rs), None
        if kind.startswith("ror"):
            return ("(((u32)(%s) >> ((%s) & 31u)) | ((u32)(%s) << (32u - ((%s) & 31u))))"
                    % (rm, rs, rm, rs)), None
        raise Unsupported("shift %r" % op2)
    n = parse_int(amt) if amt.startswith("#") else (32 if kind.startswith("lsr") else 0)
    if kind.startswith("lsl"):
        if n == 0:
            return rm, None
        if n >= 32:
            return "0u", ("((%s) & 1u)" % rm if n == 32 else "0u")
        return "((u32)(%s) << %d)" % (rm, n), "((u32)(%s) >> %d)" % (rm, 32 - n)
    if kind.startswith("lsr"):
        if n == 0:
            n = 32
        if n >= 32:
            return "0u", "((u32)(%s) >> 31)" % rm
        return "((u32)(%s) >> %d)" % (rm, n), "((u32)(%s) >> %d)" % (rm, n - 1)
    if kind.startswith("asr"):
        if n >= 32:
            return "((u32)((s32)(%s) >> 31))" % rm, "((u32)(%s) >> 31)" % rm
        return "((u32)((s32)(%s) >> %d))" % (rm, n), "(((u32)(%s) >> %d) & 1u)" % (rm, n - 1)
    if kind.startswith("ror"):
        if not amt:
            return "((fC ? 0x80000000u : 0u) | ((u32)(%s) >> 1))" % rm, "((%s) & 1u)" % rm
        n = n % 32
        if n == 0:
            return rm, "((u32)(%s) >> 31)" % rm
        return "(((u32)(%s) >> %d) | ((u32)(%s) << %d))" % (rm, n, rm, 32 - n), "((u32)(%s) >> %d)" % (rm, n - 1)
    if kind == "rrx":
        return "((fC ? 0x80000000u : 0u) | ((u32)(%s) >> 1))" % rm, "((%s) & 1u)" % rm
    raise Unsupported("shifter %r" % op2)


def offset_expr(off):
    off = off.strip()
    if off.startswith("#"):
        v = parse_int(off)
        return ("0x%Xu" % (v & 0xFFFFFFFF)) if v >= 0 else ("-0x%Xu" % (-v))
    return shifter(off)[0]


def mem_addr(rn, off, wb_pre, post):
    """Addressing-mode parse -> (addr_expr, writeback_expr_or_None)."""
    if post is not None:
        pexpr = offset_expr(post)
        wb = ("(%s + %s)" % (rn, pexpr)) if pexpr != "0u" else rn
        return rn, wb
    oexpr = offset_expr(off) if off is not None else "0u"
    addr = ("(%s + %s)" % (rn, oexpr)) if oexpr != "0u" else rn
    return addr, (addr if wb_pre else None)


ALU_LOGIC = ("and", "orr", "eor", "bic", "mov", "mvn")
ALU_TEST = ("cmp", "cmn", "tst", "teq")


def translate(ins, ctx):
    """Translate one instruction to a list of C lines (raises Unsupported)."""
    mnem, cond = split_cond(ins.mnemonic)
    ops = ins.op_str
    base = mnem.split(".")[0]
    setf = mnem.endswith("s") and base not in ("ldrsb", "ldrsh") \
        and not mnem.startswith(("ldm", "stm", "push", "pop"))
    lines = []

    def emit(stmt):
        lines.append(stmt)

    # ---- branches / returns ----
    if base in ("b", "bl", "blx", "bx"):
        t = branch_target(ins)
        if base == "bx":
            rm = reg(ops)
            if rm == "lr":
                emit("return r0;")
            else:
                ctx["warnings"].append("indirect branch bx %s at %08X modeled as tail call" % (rm, ins.address))
                emit("return ((u32 (*)(u32, u32, u32, u32))%s)(r0, r1, r2, r3);" % rm)
        elif base == "blx" and t is None:
            rm = reg(ops)
            ctx["warnings"].append("indirect call blx %s at %08X modeled as function-pointer call" % (rm, ins.address))
            emit("r0 = ((u32 (*)(u32, u32, u32, u32))%s)(r0, r1, r2, r3);" % rm)
            emit("lr = 0x%08Xu;" % (ins.address + 4))
        elif t is not None:
            if base == "b":
                if ctx["start"] <= t < ctx["ce"]:
                    emit("goto L_%08X;" % t)
                elif t in ctx["starts"] or t == ctx["end"]:
                    emit("return %s(r0, r1, r2, r3);" % ctx["ext_name"](t, ins.address))
                else:
                    raise Unsupported("branch to non-start %08X" % t)
            else:
                emit("r0 = %s(r0, r1, r2, r3);" % ctx["ext_name"](t, ins.address))
                emit("lr = 0x%08Xu;" % (ins.address + 4))
        else:
            raise Unsupported("branch form %s %s" % (mnem, ops))
    elif base == "mov" and ops.split(",")[0].strip() == "pc":
        rm = reg(ops.split(",")[1])
        if rm == "lr":
            emit("return r0;")
        else:
            ctx["warnings"].append("mov pc, %s at %08X modeled as tail call" % (rm, ins.address))
            emit("return ((u32 (*)(u32, u32, u32, u32))%s)(r0, r1, r2, r3);" % rm)
    elif base == "ldr" and ops.split(",")[0].strip() == "pc":
        if re.search(r"\[pc, \w+, lsl #", ops):
            rm = reg(re.search(r"\[pc, (\w+),", ops).group(1))
            table = []
            j = ins.address + 8
            while j < ctx["end"] and len(table) < 4096:
                v = ctx["img"].try_word(j)
                if v is None or not (ctx["start"] <= v < ctx["end"] or v in ctx["starts"]):
                    break
                table.append(v)
                j += 4
            if not table:
                raise Unsupported("empty jump table at %08X" % ins.address)
            emit("switch (%s) {" % rm)
            for i, v in enumerate(table):
                if ctx["start"] <= v < ctx["ce"]:
                    emit("    case %d: goto L_%08X;" % (i, v))
                elif v in ctx["starts"] or v == ctx["end"]:
                    emit("    case %d: return %s(r0, r1, r2, r3);" % (i, ctx["ext_name"](v, ins.address)))
                else:
                    raise Unsupported("jump-table entry %08X outside function" % v)
            ctx["warnings"].append("jump table at %08X with %d entries; out-of-range index returns 0"
                                   % (ins.address, len(table)))
            emit("    default: return 0;")
            emit("}")
        else:
            m2 = re.search(r"\[pc, #(-?0x[0-9a-f]+|-?\d+)\]", ops)
            if not m2:
                raise Unsupported("ldr pc form %s" % ops)
            v = ctx["img"].try_word(ins.address + 8 + int(m2.group(1), 0))
            if v is None:
                raise Unsupported("ldr pc pool word outside image")
            if ctx["start"] <= v < ctx["ce"]:
                emit("goto L_%08X;" % v)
            elif v in ctx["starts"] or v == ctx["end"]:
                emit("return %s(r0, r1, r2, r3);" % ctx["ext_name"](v, ins.address))
            else:
                raise Unsupported("ldr pc -> non-start %08X" % v)
    # ---- stack block transfers ----
    elif base in ("push", "pop", "stmdb", "stmfd", "ldmia", "ldmfd"):
        if base in ("push", "stmdb", "stmfd"):
            for r in reg_list(ops):
                emit("sp = sp - 4u;")
                emit("LIFT_ST32(sp, %s);" % r)
        else:
            returned = False
            for r in reg_list(ops):
                if r == "pc":
                    emit("return r0;")
                    returned = True
                    ctx["warnings"].append("pop {...,pc} at %08X modeled as return r0" % ins.address)
                else:
                    emit("%s = LIFT_LD32(sp);" % r)
                    emit("sp = sp + 4u;")
            if not returned:
                raise Unsupported("block load without pc %s %s" % (mnem, ops))
    # ---- PC-relative constants (before the generic ALU/memory paths) ----
    elif base == "ldr" and "[pc" in ops:
        rd = reg(ops.split(",")[0])
        m = re.search(r"\[pc, #(-?0x[0-9a-f]+|-?\d+)\]", ops)
        v = ctx["img"].try_word(ins.address + 8 + int(m.group(1), 0))
        if v is None:
            raise Unsupported("pool word outside image at %08X" % ins.address)
        note = ctx["syms"].get(v)
        emit("%s = 0x%08Xu; /* pool%s */" % (rd, v, " " + note if note else ""))
    elif base in ("add", "sub") and reg(ops.split(",")[1]) == "pc":
        parts = [p.strip() for p in ops.split(",")]
        v = parse_int(parts[2])
        tgt = (ins.address + 8 + v) if base == "add" else (ins.address + 8 - v)
        emit("%s = 0x%08Xu; /* adr */" % (reg(parts[0]), tgt & 0xFFFFFFFF))
    # ---- multiply family ----
    elif base in ("mul", "mla", "umull", "umlal", "smull", "smlal"):
        parts = [reg(p) for p in ops.split(",")]
        if base == "mul":
            rd, rm, rs = parts
            emit("%s = (u32)(%s) * (u32)(%s);" % (rd, rm, rs))
            if setf:
                emit("fN = %s >> 31; fZ = (%s == 0);" % (rd, rd))
        elif base == "mla":
            rd, rm, rs, rn = parts
            emit("%s = (u32)((u32)(%s) * (u32)(%s) + (u32)(%s));" % (rd, rm, rs, rn))
            if setf:
                emit("fN = %s >> 31; fZ = (%s == 0);" % (rd, rd))
        else:
            rdlo, rdhi, rm, rs = parts
            cast = "(s64)(%s)" if base[0] == "s" else "(u64)(u32)(%s)"
            emit("{ u64 _t = (u64)%s * (u64)%s; %s = (u32)_t; %s = (u32)(_t >> 32); }"
                 % (cast % rm, cast % rs, rdlo, rdhi))
            if setf:
                emit("fN = %s >> 31; fZ = (%s == 0);" % (rdlo, rdlo))
    # ---- data processing ----
    elif base in ALU_LOGIC or base in ALU_TEST or base in ("add", "sub", "rsb") \
            or base in ("lsl", "lsr", "asr", "ror", "rrx"):
        parts = [p.strip() for p in ops.split(",")]
        if base in ("mov", "mvn"):
            rd, a, op2 = reg(parts[0]), None, ", ".join(parts[1:])
        elif base in ALU_TEST:
            rd, a, op2 = None, reg(parts[0]), ", ".join(parts[1:])
        elif base in ("lsl", "lsr", "asr", "ror", "rrx"):
            rd = reg(parts[0])
            rm = reg(parts[1])
            op2 = rm if len(parts) == 2 else "%s, %s, %s" % (rm, base, parts[2])
            a, base = None, "mov"
        else:
            rd, a, op2 = reg(parts[0]), reg(parts[1]), ", ".join(parts[2:])
        test = base in ALU_TEST
        expr, carry = shifter(op2, allow_carry=not (setf or test))
        if base == "mov":
            res = expr
        elif base == "mvn":
            res = "~(%s)" % expr
        elif base == "add":
            res = "(%s + %s)" % (a, expr)
        elif base == "sub":
            res = "(%s - %s)" % (a, expr)
        elif base == "rsb":
            res = "(%s - %s)" % (expr, a)
        elif base == "and":
            res = "(%s & %s)" % (a, expr)
        elif base == "orr":
            res = "(%s | %s)" % (a, expr)
        elif base == "eor":
            res = "(%s ^ %s)" % (a, expr)
        elif base == "bic":
            res = "(%s & ~(%s))" % (a, expr)
        elif base == "cmp":
            res = "(%s - %s)" % (a, expr)
        elif base == "cmn":
            res = "(%s + %s)" % (a, expr)
        elif base == "tst":
            res = "(%s & %s)" % (a, expr)
        elif base == "teq":
            res = "(%s ^ %s)" % (a, expr)
        else:
            raise Unsupported("alu %s" % mnem)
        if rd and not test:
            emit("%s = %s;" % (rd, res))
        if setf or test:
            if base in ("add", "cmn"):
                emit("{ u32 _a = (u32)(%s), _b = (u32)(%s), _r = (u32)%s;" % (a, expr, res))
                emit("  fC = (u32)(((u64)_a + (u64)_b) >> 32); fV = ((~(_a ^ _b) & (_a ^ _r)) >> 31);")
                emit("  fN = _r >> 31; fZ = (_r == 0); }")
            elif base in ("sub", "rsb", "cmp"):
                ra, rb = (a, expr) if base in ("sub", "cmp") else (expr, a)
                emit("{ u32 _a = (u32)(%s), _b = (u32)(%s), _r = (u32)%s;" % (ra, rb, res))
                emit("  fC = (_a >= _b); fV = (((_a ^ _b) & (_a ^ _r)) >> 31);")
                emit("  fN = _r >> 31; fZ = (_r == 0); }")
            else:
                src = rd if rd else "(%s)" % res
                if carry:
                    emit("fC = %s;" % carry)
                emit("fN = ((u32)(%s)) >> 31; fZ = ((u32)(%s)) == 0;" % (src, src))
    # ---- memory ----
    elif base in WIDTH or base in ("ldrd", "strd"):
        if base in ("ldrd", "strd"):
            parts = [p.strip() for p in ops.split(",")]
            rd, rd2 = reg(parts[0]), reg(parts[1])
            m = ADDR_RE.match(", ".join(parts[1:]))
            if not m:
                raise Unsupported("%s %s" % (mnem, ops))
            rn = reg(m.group(2))
            addr, wb = mem_addr(rn, m.group(3), m.group(4), m.group(5))
            if base == "ldrd":
                emit("%s = LIFT_LD32(%s);" % (rd, addr))
                emit("%s = LIFT_LD32(%s + 4u);" % (rd2, addr))
            else:
                emit("LIFT_ST32(%s, %s);" % (addr, rd))
                emit("LIFT_ST32(%s + 4u, %s);" % (addr, rd2))
            if wb:
                emit("%s = %s;" % (rn, wb))
        else:
            m = ADDR_RE.match(ops)
            if not m:
                raise Unsupported("addressing %s %s" % (mnem, ops))
            rd, rn = reg(m.group(1)), reg(m.group(2))
            addr, wb = mem_addr(rn, m.group(3), m.group(4), m.group(5))
            _w, ld, st = WIDTH[base]
            if base.startswith("st"):
                emit("%s(%s, %s);" % (st, addr, rd))
            else:
                emit("%s = %s(%s);" % (rd, ld, addr))
            if wb:
                emit("%s = %s;" % (rn, wb))
    else:
        raise Unsupported("instruction %s %s" % (mnem, ops))

    if cond != "al" and lines:
        c = COND_EXPR[cond]
        if c is not None:
            lines = ["if (%s) {" % c] + ["    " + l for l in lines] + ["}"]
            if not ctx["flags_set"]:
                ctx["warnings"].append(
                    "conditional %s at %08X reads flags before any update (modeled as 0)" % (mnem, ins.address))
    if setf or base in ALU_TEST:
        ctx["flags_set"] = True
    return lines


